import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { computeLicenseManifestSha256 } from "../src/licensing/licenseConfig.js";
import { loadUiUpdateConfig } from '../src/updates/uiUpdateConfig.js';
import {
  isProtectedComputeTestFixtureCampaign,
  isProtectedComputeTestFixtureHostname,
  loadProtectedComputeDistribution,
  PROTECTED_COMPUTE_RESOURCE_PATHS,
} from "../src/licensing/protectedComputeDistribution.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const projectPath = path.join(root, "resources", "project.json");
const distributionPath = path.join(root, "resources", "distribution.json");
const outputPath = path.join(root, "src", "licensing", "sealedLicenseManifest.js");
const project = JSON.parse(fs.readFileSync(projectPath, "utf8"));
const distribution = JSON.parse(fs.readFileSync(distributionPath, "utf8"));
const licenseRoot = path.join(root, "resources");
loadUiUpdateConfig({ value: distribution.ui_update, licenseRoot, serverUrl: distribution.license_center_url });

if (distribution.license_mode !== "enforce") throw new Error("正式安装包必须使用 enforce 模式");
if (distribution.project_code !== project.code) throw new Error("项目代码不一致");
if (!/^[a-f0-9]{64}$/u.test(distribution.offline_key_sha256 || "")) {
  throw new Error("缺少有效的离线公钥 SHA-256 指纹");
}
if (Boolean(distribution.channel_code) !== Boolean(distribution.distribution_token)) {
  throw new Error("渠道代码和分发 Token 必须同时存在或同时留空");
}
const server = new URL(distribution.license_center_url);
if (server.protocol !== "https:") throw new Error("正式安装包的 License Center 必须使用 HTTPS");
if (isProtectedComputeTestFixtureHostname(server.hostname)) {
  throw new Error("正式安装包的 License Center 不能使用占位、文档保留、临时隧道、localhost 或 loopback 主机");
}
if (isProtectedComputeTestFixtureCampaign(distribution.campaign_code)) {
  throw new Error("正式安装包不能使用 test/fixture 活动代码");
}

const protectedComputeDirectory = path.join(licenseRoot, "protected-compute");
const permittedProtectedComputeFiles = new Set([
  "README.md",
  path.basename(PROTECTED_COMPUTE_RESOURCE_PATHS.configurationPublicKey),
  path.basename(PROTECTED_COMPUTE_RESOURCE_PATHS.signedConfig),
]);
for (const entry of fs.readdirSync(protectedComputeDirectory, { withFileTypes: true })) {
  if (!entry.isFile() || entry.isSymbolicLink() || !permittedProtectedComputeFiles.has(entry.name)) {
    throw new Error(`受保护计算发布目录包含未批准资源：${entry.name}`);
  }
}
loadProtectedComputeDistribution({
  distribution,
  licenseRoot,
  expectedServerUrl: distribution.license_center_url,
  required: true,
  minimumRemainingMs: 24 * 60 * 60 * 1000,
});

const digest = computeLicenseManifestSha256(projectPath, distributionPath);
const existingSource = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
const v2Digest = existingSource.match(
  /SEALED_LICENSE_MANIFEST_SHA256_V2\s*=\s*["']([a-f0-9]{64})["']/u,
)?.[1] || "";
if (!v2Digest) throw new Error("缺少 V2 License 配置摘要，禁止覆盖双发行清单");
const temporary = `${outputPath}.${process.pid}.tmp`;
fs.writeFileSync(
  temporary,
  [
    "// Generated by scripts/seal-license-manifest.mjs immediately before packaging.",
    `export const SEALED_LICENSE_MANIFEST_SHA256 = ${JSON.stringify(digest)};`,
    `export const SEALED_LICENSE_MANIFEST_SHA256_V2 = ${JSON.stringify(v2Digest)};`,
    "export const SEALED_LICENSE_MANIFEST_SHA256_ALLOWLIST = Object.freeze([",
    "  SEALED_LICENSE_MANIFEST_SHA256,",
    "  SEALED_LICENSE_MANIFEST_SHA256_V2,",
    "]);",
    "",
  ].join("\n"),
  "utf8",
);
fs.renameSync(temporary, outputPath);
process.stdout.write(`License manifest sealed: ${digest.slice(0, 12)}\n`);
