export function saveUnitShop(shopRepository, id = "shop_unit") {
  shopRepository.saveShop({
    id,
    name: `Unit shop ${id}`,
    ["client" + "Id"]: `client-${id}`,
    ["api" + "Key"]: `key-${id}`,
    status: "active",
  });
  return id;
}
