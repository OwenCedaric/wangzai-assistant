import { DATA_DOMAIN_REGISTRY } from '../data/dataDomainRegistry.js';
import { createRecoverySqliteSnapshot } from './recoverySqliteSnapshot.js';

const quote = (value) => `"${String(value).replaceAll('"', '""')}"`;
const scopeKey = (shopId, policy) => JSON.stringify([shopId, policy.domain]);
const shopPolicies = DATA_DOMAIN_REGISTRY.filter((policy) => (
  policy.scopeType === 'shop' && policy.backup !== 'excluded'
  && policy.storageAdapter !== 'secret-vault' && policy.recoveryChannel !== 'profile-core'
));
const stateTables = ['shop_product_storage_state', 'shop_order_storage_state', 'shop_operational_storage_state'];
let sessionSequence = 0;

function fail(code) {
  const error = new Error(code);
  error.code = code;
  throw error;
}

function databasePath(db) {
  return String(db.prepare('PRAGMA database_list').all().find((row) => row.name === 'main')?.file || '');
}

function attachedTableDatabase(db, alias, tables) {
  const names = tables.map((table) => String(table).replace(/[.*+?^${}()|[\]\\]/gu, '\\$&')).join('|');
  const references = new RegExp(`(\\b(?:FROM|JOIN|INTO|UPDATE)\\s+)(?:"(${names})"|(${names}))(?=\\s|\\(|$)`, 'giu');
  return Object.freeze({
    prepare(sql) {
      const text = String(sql);
      if (/^\s*PRAGMA\s+table_info\(/iu.test(text)) {
        return db.prepare(text.replace(/PRAGMA\s+table_info/iu, `PRAGMA ${quote(alias)}.table_info`));
      }
      // Only SQL generated by the recovery codecs reaches this facade. Values
      // stay parameter-bound; callers cannot supply arbitrary database names.
      return db.prepare(text.replace(references, (_match, prefix, quotedName, bareName) =>
        `${prefix}${quote(alias)}.${quote(quotedName || bareName)}`));
    },
  });
}

/**
 * One authority map shared by previews, snapshots, imports and readback.
 * Profile/secret channels remain on the profile database. The application
 * resolver must fail closed for a cut-over domain whose shop store is not ready.
 */
export function createRecoveryStorageAdapter({ db, resolveShopDomainDatabase = () => ({ db }) } = {}) {
  if (!db?.prepare || !db?.exec) throw new Error('RECOVERY_STORAGE_DATABASE_REQUIRED');
  if (typeof resolveShopDomainDatabase !== 'function') throw new Error('RECOVERY_STORAGE_RESOLVER_REQUIRED');
  const snapshotRoutes = new WeakMap();
  let importSession = null;

  function authority(shopId, policy) {
    if (policy.scopeType !== 'shop' || policy.storageAdapter === 'secret-vault'
      || policy.recoveryChannel === 'profile-core') return db;
    const result = resolveShopDomainDatabase({ shopId, policy, domain: policy.domain, canonicalTable: policy.canonicalTable });
    const resolved = result?.db || result;
    if (!resolved?.prepare) fail('RECOVERY_STORAGE_AUTHORITY_UNAVAILABLE');
    return resolved;
  }

  function resolveDatabase({ db: sourceDb = db, shopId, policy }) {
    const snapshots = snapshotRoutes.get(sourceDb);
    if (snapshots) return snapshots.get(scopeKey(shopId, policy)) || sourceDb;
    if (sourceDb !== db) return sourceDb; // Explicit legacy/staging database.
    if (importSession?.shopId === shopId) {
      return importSession.routes.get(scopeKey(shopId, policy)) || db;
    }
    return authority(shopId, policy);
  }

  function createSnapshot({ shopIds } = {}) {
    const selected = shopIds || db.prepare("SELECT id FROM shops WHERE status != 'inactive' ORDER BY id").all().map((row) => row.id);
    const authorities = new Map();
    for (const shopId of selected) {
      for (const policy of shopPolicies) authorities.set(scopeKey(shopId, policy), authority(shopId, policy));
    }
    const snapshots = new Map();
    try {
      for (const source of new Set([db, ...authorities.values()])) snapshots.set(source, createRecoverySqliteSnapshot({ db: source }));
      // Identity/routing changes during collection cannot silently publish a
      // snapshot for a former shop incarnation.
      for (const shopId of selected) {
        for (const policy of shopPolicies) {
          if (authority(shopId, policy) !== authorities.get(scopeKey(shopId, policy))) fail('RECOVERY_STORAGE_SCOPE_CHANGED');
        }
      }
      const central = snapshots.get(db);
      snapshotRoutes.set(central.db, new Map([...authorities].map(([key, source]) => [key, snapshots.get(source).db])));
      const evidence = snapshots.size === 1 ? central.evidence : Object.freeze({
        ...central.evidence,
        method: 'per-authority-vacuum-into',
        databaseCount: snapshots.size,
        // Each immutable database is internally consistent. This is not a
        // promise of a distributed point-in-time snapshot across live WALs.
        crossDatabaseAtomicSnapshot: false,
      });
      let disposed = false;
      return {
        db: central.db, evidence,
        dispose() {
          if (disposed) return;
          disposed = true;
          snapshotRoutes.delete(central.db);
          for (const snapshot of [...snapshots.values()].reverse()) snapshot.dispose();
        },
      };
    } catch (error) {
      for (const snapshot of [...snapshots.values()].reverse()) snapshot.dispose();
      throw error;
    }
  }

  function withSnapshot(options, build) {
    const snapshot = createSnapshot(options);
    try { return build(snapshot.db, snapshot.evidence); } finally { snapshot.dispose(); }
  }

  function selectedImportPolicies(domains) {
    if (!domains) return shopPolicies;
    const selected = new Set(domains.map((domain) => typeof domain === 'string' ? domain : domain.domain));
    return shopPolicies.filter((policy) => selected.has(policy.domain));
  }

  function getImportSafety({ shopId, domains } = {}) {
    const external = shopId ? [...new Set(selectedImportPolicies(domains).map((policy) => authority(shopId, policy)).filter((source) => source !== db))] : [];
    if (!external.length) return Object.freeze({ writeAllowed: true, atomicity: 'single-database', errorCode: null });
    const databases = [db, ...external];
    const safe = databases.every((source) => databasePath(source)
      && ['delete', 'truncate', 'persist'].includes(String(source.prepare('PRAGMA journal_mode').get()?.journal_mode).toLowerCase()));
    return Object.freeze({ writeAllowed: safe, atomicity: safe ? 'attached-rollback-journal' : 'safe-offline-restore-required',
      errorCode: safe ? null : 'DATA_BACKUP_IMPORT_SAFE_RESTORE_REQUIRED' });
  }

  function openImportSession({ shopId, domains } = {}) {
    if (importSession) fail('DATA_BACKUP_IMPORT_ALREADY_ACTIVE');
    if (!shopId) return { dispose() {}, markWritten() {}, atomicity: 'single-database' };
    const sources = new Map(shopPolicies.map((policy) => [policy, authority(shopId, policy)]));
    const writtenPolicies = new Set(selectedImportPolicies(domains));
    const external = [...new Set([...sources].filter(([policy]) => writtenPolicies.has(policy)).map(([, source]) => source).filter((source) => source !== db))];
    if (!external.length) return { dispose() {}, markWritten() {}, atomicity: 'single-database' };
    // SQLite's one-connection ATTACH transaction rolls back ordinary failures,
    // but WAL (or an in-memory main DB) does not offer crash-atomic multi-file
    // commits. Never advertise such an online restore as safely committed.
    if (!getImportSafety({ shopId, domains }).writeAllowed) {
      fail('DATA_BACKUP_IMPORT_SAFE_RESTORE_REQUIRED');
    }
    const aliases = new Map();
    const routes = new Map();
    let previousSynchronous = null;
    try {
      for (const source of external) {
        const alias = `recovery_import_${++sessionSequence}`;
        db.prepare(`ATTACH DATABASE ? AS ${quote(alias)}`).run(databasePath(source));
        aliases.set(source, alias);
        const journalMode = String(db.prepare(`PRAGMA ${quote(alias)}.journal_mode`).get()?.journal_mode).toLowerCase();
        if (!['delete', 'truncate', 'persist'].includes(journalMode)) fail('DATA_BACKUP_IMPORT_SAFE_RESTORE_REQUIRED');
        db.exec(`PRAGMA ${quote(alias)}.synchronous = FULL`);
      }
      previousSynchronous = Number(db.prepare('PRAGMA main.synchronous').get()?.synchronous);
      db.exec('PRAGMA main.synchronous = FULL');
      const databaseFacades = new Map([...aliases].map(([source, alias]) => [source,
        attachedTableDatabase(db, alias, [...sources].filter(([, candidate]) => candidate === source).map(([policy]) => policy.canonicalTable)),
      ]));
      for (const [policy, source] of sources) {
        routes.set(scopeKey(shopId, policy), databaseFacades.get(source) || source);
      }
      const session = { shopId, routes };
      importSession = session;
      let disposed = false;
      return {
        atomicity: 'attached-rollback-journal',
        markWritten(domains = []) {
          const changed = new Set(domains.filter((domain) => Number(domain.inserted) + Number(domain.updated) > 0).map((domain) => domain.domain));
          const changedSources = new Set([...sources].filter(([policy]) => changed.has(policy.domain)).map(([, source]) => source));
          for (const source of changedSources) {
            const alias = aliases.get(source);
            if (!alias) continue;
            for (const table of stateTables) {
              const columns = db.prepare(`PRAGMA ${quote(alias)}.table_info(${quote(table)})`).all().map((row) => row.name);
              if (!columns.includes('direct_write_revision')) continue;
              const mode = columns.includes('write_mode') ? 'write_mode' : 'mode';
              const time = columns.includes('updated_at') ? 'updated_at' : 'last_verified_at';
              db.prepare(`UPDATE ${quote(alias)}.${quote(table)} SET direct_write_revision = direct_write_revision + 1,
                ${quote(time)} = ?, last_error_code = NULL WHERE singleton = 1 AND ${quote(mode)} = 'direct'`)
                .run(new Date().toISOString());
            }
          }
        },
        dispose() {
          if (disposed) return;
          disposed = true;
          if (importSession === session) importSession = null;
          try {
            for (const alias of [...aliases.values()].reverse()) db.exec(`DETACH DATABASE ${quote(alias)}`);
          } finally {
            db.exec(`PRAGMA main.synchronous = ${previousSynchronous}`);
          }
        },
      };
    } catch (error) {
      for (const alias of [...aliases.values()].reverse()) {
        try { db.exec(`DETACH DATABASE ${quote(alias)}`); } catch { /* preserve admission error */ }
      }
      if (previousSynchronous !== null) db.exec(`PRAGMA main.synchronous = ${previousSynchronous}`);
      throw error;
    }
  }

  return Object.freeze({ resolveDatabase, createSnapshot, withSnapshot, openImportSession, getImportSafety });
}
