const DEFAULT_RETRY = Object.freeze({
  maxAttempts: 3,
  baseDelayMs: 600,
  maxDelayMs: 6_000,
  retryOnStatus: Object.freeze([408, 425, 429, 500, 502, 503, 504]),
  respectRetryAfter: true,
});

function freezePlanning(endpoint = {}) {
  const planning = endpoint.planning || {};
  const mode =
    planning.mode ||
    endpoint.pagination?.mode ||
    endpoint.batching?.mode ||
    "single";
  return Object.freeze({
    mode,
    arrayParam: planning.arrayParam || endpoint.batching?.arrayParam || null,
    limitParam:
      planning.limitParam || endpoint.pagination?.limitField || "limit",
    offsetParam:
      planning.offsetParam || endpoint.pagination?.offsetField || "offset",
    cursorParam: planning.cursorParam || "cursor",
    nextCursorPath: planning.nextCursorPath || "result.cursor",
    hasNextPath: planning.hasNextPath || "result.has_next",
    lastIdParam: planning.lastIdParam || "last_id",
    nextLastIdPath: planning.nextLastIdPath || "result.last_id",
    dateFromParam: planning.dateFromParam || "since",
    dateToParam: planning.dateToParam || "to",
    maxLimit: planning.maxLimit ?? endpoint.pagination?.maxLimit ?? 100,
    defaultLimit:
      planning.defaultLimit ?? endpoint.pagination?.defaultLimit ?? 100,
    maxPages:
      planning.maxPages ??
      endpoint.pagination?.maxPages ??
      (mode === "single" ? 1 : 20),
    maxBatches: planning.maxBatches ?? endpoint.batching?.maxBatches ?? 100,
    batchSize: planning.batchSize ?? endpoint.batching?.size ?? 100,
    windowDays: planning.windowDays ?? 7,
    stopOnEmpty: planning.stopOnEmpty !== false,
    stopOnShortPage: planning.stopOnShortPage === true,
    stopOnDuplicateCursor: planning.stopOnDuplicateCursor !== false,
    stopOnDuplicateLastId: planning.stopOnDuplicateLastId !== false,
    stopOnDuplicatePayload: planning.stopOnDuplicatePayload !== false,
    currentPageFirst:
      planning.currentPageFirst === true || mode === "current_page_first",
    report: planning.report ? Object.freeze({ ...planning.report }) : null,
  });
}

function freezeEndpoint(endpoint) {
  const domain = endpoint.domain || endpoint.owner || "unknown";
  const retry = Object.freeze({ ...DEFAULT_RETRY, ...(endpoint.retry || {}) });
  const rateLimit = Object.freeze({
    bucket: `${domain}.read`,
    minIntervalMs: 350,
    concurrency: 2,
    ...(endpoint.rateLimit || endpoint.rate || {}),
  });
  const cachePolicy = Object.freeze({
    storage: "sqlite",
    ttlSeconds: 24 * 60 * 60,
    policy: "entity_snapshot",
    staleIfError: true,
    ...(endpoint.cachePolicy || endpoint.cache || {}),
  });
  const planning = freezePlanning(endpoint);
  const responseShape = Object.freeze({
    envelope: "json",
    itemsPath: "result",
    ...(endpoint.responseShape || {}),
  });

  return Object.freeze({
    method: "POST",
    timeoutMs: 15_000,
    ...endpoint,
    domain,
    retry,
    rateLimit,
    rate: rateLimit,
    cachePolicy,
    cache: cachePolicy,
    planning,
    batching: Object.freeze({
      mode: planning.mode,
      arrayParam: planning.arrayParam,
      size: planning.batchSize,
      maxBatches: planning.maxBatches,
    }),
    pagination: Object.freeze({
      mode: planning.mode,
      maxPages: planning.maxPages,
      maxLimit: planning.maxLimit,
      limitField: planning.limitParam,
      offsetField: planning.offsetParam,
      stopOnShortPage: planning.stopOnShortPage,
    }),
    responseShape,
  });
}

