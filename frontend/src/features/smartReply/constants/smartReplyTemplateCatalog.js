export const smartReplyTemplateCatalog = Object.freeze(
  Object.fromEntries(
    Object.entries(catalog).map(([scene, templates]) => [
      scene,
      Object.freeze(templates.map((template) => Object.freeze({ ...template, scene, source: 'miaoshou-default' }))),
    ])
  )
);

export function getSmartReplyTemplates(scene) {
  return smartReplyTemplateCatalog[scene] || smartReplyTemplateCatalog.passportRequired;
}
