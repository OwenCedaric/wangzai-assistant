import { describe, expect, it } from 'vitest';

import {
  buildListingAttributes,
  createCollectionProductListingDraft,
  normalizeCollectionProductListingDraft,
  normalizeCollectionProductListingDrafts,
  repairCollectionProductSkuVariantValues,
  requireManualCollectionProductCategorySelection,
  toCollectionListingCommandDraft,
  validateCollectionProductListingStep,
} from './collectionProductListingWorkflow.js';
import { buildCollectionSkuPricingInputKey } from './collectionSkuPricingIntegrity.js';

describe('collection product listing attribute workflow', () => {
  it('generates every collected SKU offer id from its 1688 SKU digits with a WZ prefix', () => {
    const normalized = normalizeCollectionProductListingDraft({}, {
      id: '1688:907805856885',
      sourceProductId: '907805856885',
      skus: [
        { id: '5934148230656', name: '黑色' },
        { id: 'sku_id=5934148230673', name: '金色' },
      ],
    });

    expect(normalized.skus.map((sku) => sku.offerId)).toEqual([
      'WZ-5934148230656',
      'WZ-5934148230673',
    ]);
  });

  it('uses a stable numeric fallback when 1688 omitted a numeric SKU id', () => {
    const product = {
      id: '1688:907805856885',
      sourceProductId: '907805856885',
      skus: [{ id: 'default', name: '默认款' }, { id: 'red', name: '红色' }],
    };
    const first = normalizeCollectionProductListingDraft({}, product);
    const reopened = normalizeCollectionProductListingDraft({ skus: first.skus }, product);

    expect(first.skus.map((sku) => sku.offerId)).toEqual(reopened.skus.map((sku) => sku.offerId));
    expect(first.skus.every((sku) => /^WZ-\d+$/u.test(sku.offerId))).toBe(true);
    expect(new Set(first.skus.map((sku) => sku.offerId)).size).toBe(2);
  });

  it('migrates only an exact legacy autogenerated SPB offer id and preserves a custom saved id', () => {
    const product = {
      id: '1688:9078',
      sourceProductId: '9078',
      skus: [{ id: '5934148230656', name: '黑色' }, { id: '5934148230673', name: '金色' }],
    };
    const normalized = normalizeCollectionProductListingDraft({
      skus: [
        { sourceSkuId: '5934148230656', offerId: 'SPB-9078-5934148230656-01' },
        { sourceSkuId: '5934148230673', offerId: 'CUSTOM-SAVED-2' },
      ],
    }, product);

    expect(normalized.skus[0].offerId).toBe('WZ-5934148230656');
    expect(normalized.skus[1].offerId).toBe('CUSTOM-SAVED-2');
  });

  it('keeps a large collected SKU set unique and inside the Ozon 30-character limit', () => {
    const normalized = normalizeCollectionProductListingDraft({}, {
      id: '1688:907805856885',
      sourceProductId: '907805856885',
      skus: Array.from({ length: 82 }, (_, index) => ({
        id: String(5934148230000 + index),
        name: `规格 ${index + 1}`,
      })),
    });
    const offerIds = normalized.skus.map((sku) => sku.offerId);

    expect(offerIds).toHaveLength(82);
    expect(new Set(offerIds).size).toBe(82);
    expect(offerIds.every((offerId) => /^WZ-\d+$/u.test(offerId) && offerId.length <= 30)).toBe(true);
  });

  it('adds a stable numeric suffix only when duplicated source SKU digits would collide', () => {
    const product = {
      id: '1688:907805856885',
      skus: [
        { id: '5934148230656', name: '黑色 A' },
        { id: 'copy-5934148230656', name: '黑色 B' },
        { id: 'duplicate-5934148230656', name: '黑色 C' },
      ],
    };
    const first = normalizeCollectionProductListingDraft({}, product);
    const second = normalizeCollectionProductListingDraft({}, product);
    const offerIds = first.skus.map((sku) => sku.offerId);

    expect(new Set(offerIds).size).toBe(3);
    expect(offerIds).toEqual(second.skus.map((sku) => sku.offerId));
    expect(offerIds.every((offerId) => /^WZ-\d+$/u.test(offerId) && offerId.length <= 30)).toBe(true);
  });

  it('persists whether the category was selected automatically or manually', () => {
    expect(normalizeCollectionProductListingDraft({ categorySelectionSource: 'manual' }).categorySelectionSource).toBe('manual');
    expect(normalizeCollectionProductListingDraft({ categorySelectionSource: 'auto' }).categorySelectionSource).toBe('auto');
    expect(normalizeCollectionProductListingDraft({ categorySelectionSource: 'unknown' }).categorySelectionSource).toBe('');
  });

  it('persists the North Bear autofill version so successful batches survive a retry', () => {
    const normalized = normalizeCollectionProductListingDraft({
      attributeAutofillVersion: 'north-bear-seven-sku-five-phase-20260901',
    });
    expect(normalized.attributeAutofillVersion).toBe('north-bear-seven-sku-five-phase-20260901');
  });

  it('invalidates legacy automatic categories until the complete catalog is confirmed', () => {
    const confirmed = requireManualCollectionProductCategorySelection(normalizeCollectionProductListingDraft({
      descriptionCategoryId: '17027904',
      typeId: '971081388',
      categorySelectionSource: 'auto',
      categoryPath: '小百货和配饰 > 配饰 > 平光眼镜',
      attributeValues: { 9048: { value: 'GB02' } },
      skus: [{ sourceSkuId: 'one', attributeValues: { 10096: { value: '黑色' } } }],
    }));

    expect(confirmed).toMatchObject({
      descriptionCategoryId: '', typeId: '', categorySelectionSource: '', categoryPath: '', attributeValues: {},
    });
    expect(confirmed.skus[0].attributeValues).toEqual({});
  });

  it('persists the activity-price upload switch and its 50% pricing snapshot', () => {
    const normalized = normalizeCollectionProductListingDraft({
      activityPriceUpload: true,
      skus: [{
        sourceSkuId: 'one', priceCny: '100', oldPriceCny: '200',
        pricingSnapshot: {
          pricingMode: 'ozon-activity-50',
          activityDiscountPercent: 50,
          activityPriceCny: 100,
          activityReferencePriceCny: 200,
          standardOldPriceCny: 130,
        },
      }],
    });

    expect(normalized.activityPriceUpload).toBe(true);
    expect(normalized.skus[0].pricingSnapshot).toMatchObject({
      pricingMode: 'ozon-activity-50',
      activityDiscountPercent: '50',
      activityPriceCny: '100',
      activityReferencePriceCny: '200',
      standardOldPriceCny: '130',
    });
  });

  it('preserves signed pricing evidence and blocks an unbound or stale SKU price', () => {
    const pricingDraft = {
      purchaseCost: '', firstMileCost: '5.33', extraCost: '', ozonFeePercent: '13',
      expectedProfitCny: '20', targetMarginPercent: '', currentPrice: '',
    };
    const baseSku = {
      sourceSkuId: 'one', sourcePriceCny: '8.4', offerId: 'WZ-1001', enabled: true,
      priceCny: '38.79', oldPriceCny: '50.43', minPriceCny: '19.4',
      pricingSnapshot: {
        quoteSource: 'server-signed', purchaseCostCny: 8.4, firstMileCostCny: 5.33,
        extraCostCny: 0, commissionPercent: 13, commissionCostCny: 5.05,
        fixedCostCny: 13.73, allInCostCny: 18.78, totalCostCny: 18.78,
        logisticsProviderId: 'guoo', logisticsRouteId: 'guoo-route', logisticsPricingVersion: '2026-08-20',
      },
    };
    const draft = normalizeCollectionProductListingDraft({
      shopId: 'shop-a', uploadShopIds: ['shop-a'], pricingDraft,
      weightG: '50', packageLengthCm: '18', packageWidthCm: '8', packageHeightCm: '2',
      skus: [baseSku],
    });
    expect(draft.skus[0].pricingSnapshot).toMatchObject({
      purchaseCostCny: '8.4', firstMileCostCny: '5.33', commissionPercent: '13',
      fixedCostCny: '13.73', allInCostCny: '18.78',
      logisticsProviderId: 'guoo', logisticsRouteId: 'guoo-route', logisticsPricingVersion: '2026-08-20',
    });
    expect(validateCollectionProductListingStep('skus', draft).errors).toContain(
      '核价条件已经变化，请重新生成 SKU 售价后再继续。',
    );

    const bound = {
      ...draft,
      skus: [{
        ...draft.skus[0],
        pricingSnapshot: {
          ...draft.skus[0].pricingSnapshot,
          inputKey: buildCollectionSkuPricingInputKey(draft.skus[0], draft.pricingDraft),
        },
      }],
    };
    expect(validateCollectionProductListingStep('skus', bound).errors).not.toContain(
      '核价条件已经变化，请重新生成 SKU 售价后再继续。',
    );
  });

  it('restores the saved upload targets without changing the product master draft', () => {
    const draft = createCollectionProductListingDraft({
      id: 'multi-shop-product',
      ozonListingDrafts: {
        'shop-a': { shopId: 'shop-a', uploadShopIds: ['shop-a', 'shop-b', 'shop-b'] },
      },
    }, {
      activeShopId: 'shop-a',
      shops: [{ id: 'shop-a' }, { id: 'shop-b' }],
    });

    expect(draft.uploadShopIds).toEqual(['shop-a', 'shop-b']);
    expect(toCollectionListingCommandDraft(draft)).not.toHaveProperty('uploadShopIds');
  });

  it('repairs a deleted legacy active shop before it becomes the hidden catalog scope', () => {
    const draft = createCollectionProductListingDraft({
      id: 'legacy-shop-product',
      ozonListingDraft: {
        shopId: 'ozon-shop-deleted',
        uploadShopIds: ['ozon-shop-deleted'],
        title: '保留的商品主档',
      },
    }, {
      activeShopId: 'ozon-shop-deleted',
      shops: [{ id: 'shop-live-a' }, { id: 'shop-live-b' }],
    });

    expect(draft).toMatchObject({
      shopId: 'shop-live-a',
      uploadShopIds: ['shop-live-a'],
      title: '保留的商品主档',
    });
  });

  it('persists SKU warehouse and stock independently for every upload shop', () => {
    const normalized = normalizeCollectionProductListingDraft({
      shopId: 'shop-a',
      skus: [{
        sourceSkuId: 'sku-1',
        stock: '100',
        warehouseId: 'warehouse-a',
        inventoryByShopId: {
          'shop-b': { stock: 35, warehouseId: 'warehouse-b' },
        },
      }],
    });

    expect(normalized.skus[0].inventoryByShopId).toEqual({
      'shop-a': { stock: '100', warehouseId: 'warehouse-a' },
      'shop-b': { stock: '35', warehouseId: 'warehouse-b' },
    });
    expect(normalized.skus[0].stock).toBe('');
    expect(normalized.skus[0].warehouseId).toBe('');
  });

  it('preserves and submits multiple Ozon dictionary values', () => {
    const definitions = [{ id: '100', isDictionary: true, isCollection: true, is_required: true, complexId: 7 }];
    const draft = normalizeCollectionProductListingDraft({
      attributeValues: {
        100: {
          value: '黑色, 金色',
          values: ['黑色', '金色'],
          dictionaryValueIds: ['200', '201'],
        },
      },
    });

    expect(validateCollectionProductListingStep('details', { ...draft, title: '完整商品标题' }, definitions).ok).toBe(true);
    expect(buildListingAttributes(draft.attributeValues, definitions)).toEqual([{
      complex_id: 7,
      id: 100,
      values: [
        { dictionary_value_id: 200, value: '黑色' },
        { dictionary_value_id: 201, value: '金色' },
      ],
    }]);
  });

  it('keeps per-SKU aspect values separate and submits each SKU with its own Ozon attribute', () => {
    const definitions = [
      { id: '10', name: '品牌', is_required: true, complexId: 0 },
      { id: '20', name: '颜色', is_required: true, isAspect: true, isDictionary: true, complexId: 9 },
    ];
    const draft = normalizeCollectionProductListingDraft({
      title: '完整商品标题',
      attributeValues: { 10: { value: '旺崽' } },
      skus: [
        { sourceSkuId: 'red', sourceSkuName: '红色', offerId: 'red-1', price: '100', oldPrice: '120', attributeValues: { 20: { dictionaryValueId: '201', value: '红色' } } },
        { sourceSkuId: 'blue', sourceSkuName: '蓝色', offerId: 'blue-1', price: '100', oldPrice: '120', attributeValues: { 20: { dictionaryValueId: '202', value: '蓝色' } } },
      ],
    });

    expect(validateCollectionProductListingStep('details', draft, definitions).ok).toBe(true);
    expect(validateCollectionProductListingStep('skus', {
      ...draft, shopId: 'shop-a', uploadShopIds: ['shop-a'],
      weightG: '100', packageLengthCm: '10', packageWidthCm: '10', packageHeightCm: '10',
    }, definitions).ok).toBe(true);
  });

  it('blocks the next step when a required Ozon field is still empty', () => {
    const result = validateCollectionProductListingStep('details', {
      title: '完整商品标题', attributeValues: {},
    }, [{ id: '100', name: '材质', is_required: true }]);

    expect(result.ok).toBe(false);
    expect(result.errors[0]).toContain('1 个必填项');
  });

  it('keeps one canonical product master draft when the global active shop changes', () => {
    const product = {
      id: '1688:1', title: '采集商品', currency: 'CNY', purchasePrice: '12',
      skus: [{ id: 'default', name: '默认款' }],
      ozonListingDraft: {
        shopId: 'shop-a', uploadShopIds: ['shop-a', 'shop-b'], descriptionCategoryId: '100', typeId: '10',
        pricingDraft: { purchaseCost: '12', firstMileCost: '5' },
        logisticsDraft: { providerId: 'guoo', routeId: 'guoo-route', market: 'RU' },
        skus: [{ sourceSkuId: 'default', price: '900', oldPrice: '1000' }],
      },
      ozonListingDrafts: {
        'shop-a': {
          shopId: 'shop-a', descriptionCategoryId: '100', typeId: '10',
          pricingDraft: { purchaseCost: '12', firstMileCost: '5' },
          logisticsDraft: { providerId: 'guoo', routeId: 'guoo-route', market: 'RU' },
          skus: [{ sourceSkuId: 'default', price: '900', oldPrice: '1000' }],
        },
        'shop-b': {
          shopId: 'shop-b', descriptionCategoryId: '200', typeId: '20',
          pricingDraft: { purchaseCost: '12', firstMileCost: '8' },
          logisticsDraft: { providerId: 'cel', routeId: 'cel-route', market: 'RU' },
          skus: [{ sourceSkuId: 'default', price: '1200', oldPrice: '1400' }],
        },
      },
    };

    const shopA = createCollectionProductListingDraft(product, { activeShopId: 'shop-a', shops: [{ id: 'shop-a' }, { id: 'shop-b' }] });
    const shopB = createCollectionProductListingDraft(product, { activeShopId: 'shop-b', shops: [{ id: 'shop-a' }, { id: 'shop-b' }] });
    expect(shopA).toMatchObject({ shopId: 'shop-a', descriptionCategoryId: '100', pricingDraft: { firstMileCost: '5' }, logisticsDraft: { providerId: 'guoo' } });
    expect(shopA.skus[0].price).toBe('900');
    expect(shopB).toMatchObject({ shopId: 'shop-a', uploadShopIds: ['shop-a', 'shop-b'], descriptionCategoryId: '100', pricingDraft: { firstMileCost: '5' }, logisticsDraft: { providerId: 'guoo' } });
    expect(shopB.skus[0].price).toBe('900');
    expect(normalizeCollectionProductListingDrafts(product.ozonListingDrafts, product)).toHaveProperty('shop-a');
  });

  it('validates the Ozon category independently and requires upload shops only on the SKU step', () => {
    expect(validateCollectionProductListingStep('category', {
      descriptionCategoryId: '100', typeId: '10', categorySelectionSource: 'manual', uploadShopIds: [],
    }).ok).toBe(true);
    const result = validateCollectionProductListingStep('skus', {
      skus: [{ sourceSkuId: 'one', offerId: 'ONE', priceCny: '100', oldPriceCny: '120', enabled: true }],
      uploadShopIds: [], weightG: '100', packageLengthCm: '10', packageWidthCm: '10', packageHeightCm: '10',
    });
    expect(result.ok).toBe(false);
    expect(result.errors).toContain('请至少选择一个上传店铺。');
  });

  it('blocks prescription SKUs from the non-prescription glasses category', () => {
    const result = validateCollectionProductListingStep('category', {
      descriptionCategoryId: '17027904',
      typeId: '971081388',
      categorySelectionSource: 'manual',
      categoryName: '平光眼镜',
      categoryPath: '小百货和配饰 > 配饰 > 平光眼镜',
      skus: [
        { sourceSkuName: '金框茶变 -2.50', enabled: true },
        { sourceSkuName: '银框灰变 -4.00', enabled: true },
      ],
    });

    expect(result.ok).toBe(false);
    expect(result.errors[0]).toContain('视力眼镜');
  });

  it('blocks duplicate Ozon aspect combinations before preview', () => {
    const definitions = [
      { id: '9048', name: '型号', is_required: true, isAspect: false },
      { id: '10096', name: '商品颜色', is_required: false, isAspect: true },
      { id: '10097', name: '颜色名称', is_required: false, isAspect: true },
    ];
    const baseSku = {
      priceCny: '100', oldPriceCny: '130', enabled: true,
      attributeValues: {
        10096: { value: '黑色' },
        10097: { value: '黑框棕片' },
      },
    };
    const result = validateCollectionProductListingStep('skus', {
      shopId: 'shop-a', uploadShopIds: ['shop-a'],
      weightG: '50', packageLengthCm: '18', packageWidthCm: '8', packageHeightCm: '2',
      attributeValues: { 9048: { value: 'GB02' } },
      skus: [
        { ...baseSku, sourceSkuName: '黑框棕片 -2.50', offerId: 'SKU-1' },
        { ...baseSku, sourceSkuName: '黑框棕片 -4.00', offerId: 'SKU-2' },
      ],
    }, definitions);

    expect(result.ok).toBe(false);
    expect(result.errors).toEqual(expect.arrayContaining([expect.stringContaining('SKU 变体属性组合重复')]));
  });

  it('repairs machine-filled duplicate colour variants from every 1688 SKU source label', () => {
    const definitions = [
      { id: '9048', name: 'Название модели', isAspect: false },
      { id: '10096', name: 'Цвет товара', isAspect: false, isDictionary: true },
      { id: '10097', name: 'Название цвета', isAspect: false },
    ];
    const product = {
      id: '1688:1065996018461',
      skus: [
        { id: '6114480788859', name: '【帽子】蓝色' },
        { id: '6114480788860', name: '【帽子】灰白色' },
        { id: '6114480788861', name: '【帽子】浅蓝白' },
      ],
    };
    const draft = normalizeCollectionProductListingDraft({
      shopId: 'shop-a', uploadShopIds: ['shop-a'],
      weightG: '500', packageLengthCm: '19', packageWidthCm: '16', packageHeightCm: '5.5',
      attributeValues: {
        9048: { value: 'Акула Hat29 Hat30' },
        10096: { value: 'Белый', dictionaryValueId: '61571', source: 'ai' },
        10097: { value: 'Синий, серо-белый и светло-синий', source: 'ai' },
      },
      skus: product.skus.map((sku) => ({
        sourceSkuId: sku.id,
        sourceSkuName: sku.name,
        priceCny: '75.04', oldPriceCny: '150.08', enabled: true,
        attributeValues: {
          10096: { value: 'Белый', dictionaryValueId: '61571', source: 'ai' },
          10097: { value: 'Синий, серо-белый и светло-синий', source: 'ai' },
        },
      })),
    }, product);

    const repaired = repairCollectionProductSkuVariantValues(draft, product, definitions);

    expect(repaired.attributeValues).not.toHaveProperty('10096');
    expect(repaired.attributeValues).not.toHaveProperty('10097');
    expect(repaired.skus.map((sku) => sku.attributeValues['10097'].value)).toEqual([
      'Синий', 'Серо-белый', 'Светло-сине-белый',
    ]);
    expect(validateCollectionProductListingStep('skus', repaired, definitions).ok).toBe(true);
  });

  it('never overwrites manually entered duplicate variation values during automatic repair', () => {
    const definitions = [
      { id: '9048', name: 'Название модели', isAspect: false },
      { id: '10097', name: 'Название цвета', isAspect: false },
    ];
    const product = { skus: [{ id: '1', name: '蓝色' }, { id: '2', name: '灰白色' }] };
    const draft = normalizeCollectionProductListingDraft({
      attributeValues: { 9048: { value: 'Hat' } },
      skus: product.skus.map((sku) => ({
        sourceSkuId: sku.id,
        attributeValues: { 10097: { value: '手工值', source: 'manual' } },
      })),
    }, product);

    expect(repairCollectionProductSkuVariantValues(draft, product, definitions)).toBe(draft);
  });

  it('keeps every collected SKU purchase price in CNY for independent sale-price generation', () => {
    const draft = createCollectionProductListingDraft({
      id: '1688:sku-price',
      title: '多规格商品',
      currency: 'CNY',
      skus: [
        { id: 'small', name: '小号', price: '12.5' },
        { id: 'large', name: '大号', price: '19.8' },
      ],
    });

    expect(draft.skus.map((item) => item.sourcePriceCny)).toEqual(['12.5', '19.8']);
    expect(draft.skus.map((item) => item.priceCny)).toEqual(['', '']);
  });

  it('restores image history in the exact shop draft without sending UI history to Ozon', () => {
    const draft = normalizeCollectionProductListingDraft({
      shopId: 'shop-a',
      imageGenerationHistory: [{
        id: 'history-1',
        shopId: 'shop-a',
        productKey: '1688:1',
        createdAt: new Date().toISOString(),
        items: [{ sourceIndex: 0, assetId: 'asset-a', persistenceStatus: 'completed' }],
      }],
      generatedImageSelections: {
        main: {
          historyEntryId: 'history-1',
          items: [{ sourceIndex: 0, assetId: 'asset-a', imageUrl: '/api/product-images/preview/asset-a' }],
        },
      },
    });

    expect(draft.imageGenerationHistory).toHaveLength(1);
    expect(draft.generatedImageSelections.main.items[0]).toMatchObject({ sourceIndex: 0, assetId: 'asset-a' });
    expect(toCollectionListingCommandDraft(draft)).not.toHaveProperty('imageGenerationHistory');
    expect(toCollectionListingCommandDraft(draft)).not.toHaveProperty('generatedImageSelections');
  });

  it('migrates the newest saved history batch into generated slots for drafts saved before slot persistence existed', () => {
    const now = Date.now();
    const draft = normalizeCollectionProductListingDraft({
      shopId: 'shop-a',
      imageGenerationHistory: [
        {
          id: 'newest-main', shopId: 'shop-a', productKey: '1688:legacy', group: 'main',
          createdAt: new Date(now).toISOString(),
          items: [{ sourceIndex: 3, assetId: 'asset-newest', persistenceStatus: 'completed' }],
        },
        {
          id: 'older-main', shopId: 'shop-a', productKey: '1688:legacy', group: 'main',
          createdAt: new Date(now - 1_000).toISOString(),
          items: [{ sourceIndex: 0, assetId: 'asset-older', persistenceStatus: 'completed' }],
        },
      ],
    });

    expect(draft.generatedImageSelections.main).toMatchObject({
      historyEntryId: 'newest-main',
      items: [expect.objectContaining({ sourceIndex: 3, assetId: 'asset-newest' })],
    });
  });
});
