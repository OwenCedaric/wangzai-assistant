import { useMarketingActivityListState } from './useMarketingActivityListState.jsx';
import { useMarketingFiltersState } from './useMarketingFiltersState.jsx';
import { useMarketingProductPoolState } from './useMarketingProductPoolState.jsx';
import { useMarketingWriteFeedback } from './useMarketingWriteFeedback.jsx';
import { useMarketingCardsState } from './useMarketingCardsState.jsx';
import {
  getOzonPushRealtimeShopId,
  isOzonPushDomainRefreshEvent,
  OZON_PUSH_REALTIME_BROWSER_EVENT,
} from '../../../services/ozonPushRealtime.js';
import React from 'react';

export function useMarketingActivitiesPageModel({ shops, activeShopId, showReadNotice = true, isActive = true } = {}) {
  const {
    safeShops,
    selectedShopId,
    setSelectedShopId,
    activityRows,
    setActivityRows,
    productPool,
    setProductPool,
    marketingSummary,
    setMarketingSummary,
    selectedActivityId,
    setSelectedActivityId,
    selectedSourceType,
    setSelectedSourceType,
    activityFilter,
    setActivityFilter,
    productScope,
    setProductScope,
    pageSize,
    setPageSize,
    productPage,
    setProductPage,
    keyword,
    setKeyword,
    discountPercent,
    setDiscountPercent,
    appliedDiscountPercent,
    setAppliedDiscountPercent,
    hasAppliedDiscount,
    setHasAppliedDiscount,
    hasLiveActivityData,
    setHasLiveActivityData,
    isShowingCachedMarketingData,
    setIsShowingCachedMarketingData,
    isMarketingCacheRestoring,
    isReadingActivities,
    setIsReadingActivities,
    isReadingProducts,
    setIsReadingProducts,
    isReadingSummary,
    setIsReadingSummary,
    readNotice,
    setReadNotice,
    readNoticeTone,
    setReadNoticeTone,
    selectedProductIds,
    setSelectedProductIds,
    showSideProductSearch,
    marketingWriteDialog,
    setMarketingWriteDialog,
    isMarketingWriting,
    setIsMarketingWriting,
    productCardRef,
    marketingReadSeqRef,
    productReadSeqRef,
    productPoolCacheRef,
    marketingWriteDialogOpenRef,
    marketingScopeGenerationRef,
    setMarketingBackgroundNotice,
    selectedActivity,
    selectedShop,
  } = useMarketingActivityListState({
    shops,
    activeShopId,
    isActive,
  });
  const {
    filteredProducts,
    productRows,
    totalProductPages,
    currentProductPage,
    visibleProductRows,
    allProductIds,
    currentPageProductIds,
    isAllProductsSelected,
    isCurrentPageSelected,
    selectedProducts,
    selectedCount,
    skippedCount,
    planSubmitCount,
    reviewIssueCount,
    marketingStats,
    marketingReviewRows,
    marketingReminder,
    toggleProduct,
  } = useMarketingFiltersState({
    pageSize,
    productPool,
    keyword,
    productScope,
    hasAppliedDiscount,
    appliedDiscountPercent,
    productPage,
    selectedProductIds,
    isActive,
    selectedShop,
    selectedActivity,
    isShowingCachedMarketingData,
    hasLiveActivityData,
    isReadingActivities,
    isReadingProducts,
    isReadingSummary,
    selectedActivityId,
    selectedSourceType,
    activityRows,
    marketingSummary,
    setSelectedProductIds,
  });
  const {
    loadActivityProductPool,
    handleReadActivities,
    handleMarketingShopChange,
    handleProductScopeChange,
    applyDiscountPercent,
  } = useMarketingProductPoolState({
    selectedShop,
    productScope,
    productPoolCacheRef,
    pageSize,
    setProductPool,
    setSelectedProductIds,
    setProductPage,
    setActivityRows,
    activityRows,
    productPool,
    selectedActivityId,
    selectedSourceType,
    selectedProductIds,
    setMarketingBackgroundNotice,
    hasLiveActivityData,
    isActive,
    isMarketingCacheRestoring,
    setIsShowingCachedMarketingData,
    isReadingActivities,
    isReadingProducts,
    setReadNoticeTone,
    setReadNotice,
    marketingReadSeqRef,
    productReadSeqRef,
    setIsReadingActivities,
    setIsReadingProducts,
    setIsReadingSummary,
    setKeyword,
    setProductScope,
    setMarketingSummary,
    setSelectedActivityId,
    setSelectedSourceType,
    setHasLiveActivityData,
    setActivityFilter,
    marketingSummary,
    setSelectedShopId,
    filteredProducts,
    selectedActivity,
    discountPercent,
    setDiscountPercent,
    setAppliedDiscountPercent,
    setHasAppliedDiscount,
  });
  const {
    openMarketingWriteDialog,
    handleConfirmMarketingWrite,
    handleSubmitMarketingChanges,
    handleCancelMarketingActivity,
    selectCurrentPage,
    selectAllProducts,
    handleSelectActivity,
    refreshCurrentProductPool,
  } = useMarketingWriteFeedback({
    selectedProducts,
    hasLiveActivityData,
    selectedActivity,
    setReadNoticeTone,
    setReadNotice,
    isShowingCachedMarketingData,
    isReadingActivities,
    discountPercent,
    applyDiscountPercent,
    marketingWriteDialogOpenRef,
    setMarketingWriteDialog,
    marketingWriteDialog,
    isMarketingWriting,
    setIsMarketingWriting,
    selectedShop,
    productPoolCacheRef,
    setSelectedProductIds,
    currentPageProductIds,
    isCurrentPageSelected,
    allProductIds,
    isAllProductsSelected,
    setSelectedActivityId,
    setSelectedSourceType,
    setProductPage,
    setIsReadingProducts,
    productReadSeqRef,
    loadActivityProductPool,
    productScope,
    setProductPool,
    setMarketingBackgroundNotice,
    marketingScopeGenerationRef,
  });
  const {
    marketingFilterCard,
    sideProductSearch,
    currentActivityCard,
    reviewResultCard,
    executionPlanCard,
    marketingWriteConfirmDialog,
    reminderCard,
  } = useMarketingCardsState({
    selectedShopId,
    handleMarketingShopChange,
    safeShops,
    activityFilter,
    setActivityFilter,
    activityRows,
    handleSelectActivity,
    productScope,
    handleProductScopeChange,
    pageSize,
    setPageSize,
    setProductPage,
    keyword,
    setKeyword,
    showSideProductSearch,
    selectedActivity,
    marketingReviewRows,
    isReadingProducts,
    hasLiveActivityData,
    refreshCurrentProductPool,
    selectedCount,
    planSubmitCount,
    skippedCount,
    discountPercent,
    setDiscountPercent,
    handleCancelMarketingActivity,
    openMarketingWriteDialog,
    handleSubmitMarketingChanges,
    marketingWriteDialog,
    isMarketingWriting,
    marketingWriteDialogOpenRef,
    setMarketingWriteDialog,
    handleConfirmMarketingWrite,
    marketingReminder,
    reviewIssueCount,
  });

  React.useEffect(() => {
    const handleOzonProductPush = (event) => {
      if (!isOzonPushDomainRefreshEvent(event, 'products')) return;
      if (!selectedShop || getOzonPushRealtimeShopId(event) !== String(selectedShop.id || '').trim()) return;
      productPoolCacheRef.current.clear();
      if (!isActive || !selectedActivity?.id) return;
      void loadActivityProductPool(selectedActivity, selectedShop, productScope, {
        cacheOnly: true,
        pollRemote: false,
      }).catch(() => undefined);
    };
    globalThis.addEventListener?.(OZON_PUSH_REALTIME_BROWSER_EVENT, handleOzonProductPush);
    return () => globalThis.removeEventListener?.(OZON_PUSH_REALTIME_BROWSER_EVENT, handleOzonProductPush);
  }, [isActive, loadActivityProductPool, productPoolCacheRef, productScope, selectedActivity, selectedShop]);
  return {
    showReadNotice,
    activityRows,
    productScope,
    setProductPage,
    isReadingActivities,
    isReadingProducts,
    readNotice,
    setReadNotice,
    readNoticeTone,
    selectedProductIds,
    productCardRef,
    selectedActivity,
    productRows,
    totalProductPages,
    currentProductPage,
    visibleProductRows,
    allProductIds,
    currentPageProductIds,
    isAllProductsSelected,
    isCurrentPageSelected,
    selectedCount,
    marketingStats,
    toggleProduct,
    handleReadActivities,
    handleProductScopeChange,
    selectCurrentPage,
    selectAllProducts,
    handleSelectActivity,
    marketingFilterCard,
    sideProductSearch,
    currentActivityCard,
    reviewResultCard,
    executionPlanCard,
    marketingWriteConfirmDialog,
    reminderCard,
  };
}
