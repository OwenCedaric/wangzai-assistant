import { useProductBaseState } from './useProductBaseState.jsx';
import { useProductSyncState } from './useProductSyncState.jsx';
import { useProductFiltersState } from './useProductFiltersState.jsx';
import { useProductPaginationState } from './useProductPaginationState.jsx';
import { useProductSourceMaterialState } from './useProductSourceMaterialState.jsx';
import { useProductWriteState } from './useProductWriteState.jsx';
import { useProductBatchState } from './useProductBatchState.jsx';
import {
  createProductListQueryFilters,
  getProductListQueryFilterSignature,
} from '../../../entities/product/productListQuery.jsx';
import {
  getOzonProductPageErrorMessage,
  openOzonProductPage,
} from '../../../services/ozonProductPageLink.js';
import React from 'react';

export function useProductListPageModel({
  shops,
  activeShopId,
  isActive = true,
  isVisible = isActive,
  activityRuntime = null,
} = {}) {
  const {
    activeShop,
    canReadOzon,
    shop,
    setShop,
    status,
    setStatus,
    keyword,
    setKeyword,
    products,
    setProducts,
    loading,
    setLoading,
    productPerformance,
    setProductPerformance,
    productLoadError,
    setProductLoadError,
    editingProduct,
    setEditingProduct,
    savingProductId,
    setSavingProductId,
    productNotice,
    setProductNotice,
    productSourceLinks,
    setProductSourceLinks,
    productSourceSlotMap,
    setProductSourceSlotMap,
    page,
    setPage,
    pageSize,
    setPageSize,
    selectedProductKeys,
    setSelectedProductKeys,
    batchAnchorEl,
    setBatchAnchorEl,
    batchDialog,
    setBatchDialog,
    archiveConfirmDialog,
    setArchiveConfirmDialog,
    batchSaving,
    setBatchSaving,
    batchWarehouseState,
    setBatchWarehouseState,
    advancedFilterAnchorEl,
    setAdvancedFilterAnchorEl,
    advancedFilters,
    setAdvancedFilters,
    productSort,
    setProductSort,
    productRefreshToken,
    setProductRefreshToken,
    productRefreshProgress,
    setProductRefreshProgress,
    productPageLoading,
    setProductPageLoading,
    isProductPageTransitionPending,
    startProductPageTransition,
    loadRequestRef,
    loadAbortRef,
    productRefreshRunRef,
    batchWarehouseRequestRef,
    productMirrorScopeShops,
    productMirrorScopeKey,
    localProductMirrorStatusCounts,
    setLocalProductMirrorStatusCounts,
    localProductServerPageMeta,
    setLocalProductServerPageMeta,
  } = useProductBaseState({
    shops,
    activeShopId,
    isActive,
  });
  const productFilters = useProductFiltersState({
    activeShop,
    advancedFilterAnchorEl,
    advancedFilters,
    status,
    setAdvancedFilters,
    setProductSort,
    setPage,
    productSort,
    shop,
    keyword,
  });
  const productListQueryFilters = React.useMemo(
    () =>
      createProductListQueryFilters({
        selectedMaterialSourceFilters: productFilters.selectedMaterialSourceFilters,
        selectedWarehouseFilters: productFilters.selectedWarehouseFilters,
        productDefaultWarehouseId: productFilters.productDefaultWarehouseId,
        selectedStockFilters: productFilters.selectedStockFilters,
        selectedProductStatusFilters: productFilters.selectedProductStatusFilters,
        selectedSourceStatusFilters: productFilters.selectedSourceStatusFilters,
      }),
    [
      productFilters.productDefaultWarehouseId,
      productFilters.selectedMaterialSourceFilters,
      productFilters.selectedProductStatusFilters,
      productFilters.selectedSourceStatusFilters,
      productFilters.selectedStockFilters,
      productFilters.selectedWarehouseFilters,
    ]
  );
  const productListQueryFilterSignature = React.useMemo(
    () => getProductListQueryFilterSignature(productListQueryFilters),
    [productListQueryFilters]
  );
  const { loadOzonProducts, handleRefreshProducts } = useProductSyncState({
    isActive,
    activityRuntime,
    loadRequestRef,
    loadAbortRef,
    setProductLoadError,
    setLoading,
    setProductPageLoading,
    status,
    keyword,
    pageSize,
    page,
    productSort,
    productListQueryFilters,
    productListQueryFilterSignature,
    productMirrorScopeShops,
    setLocalProductMirrorStatusCounts,
    productMirrorScopeKey,
    setProducts,
    setLocalProductServerPageMeta,
    setProductPerformance,
    productRefreshProgress,
    productRefreshRunRef,
    setProductRefreshToken,
    setProductRefreshProgress,
    productRefreshToken,
  });
  const {
    savedDefaultWarehouseIds,
    advancedFilterOpen,
    hasAdvancedFilters,
    advancedFilterGroups,
    toggleAdvancedFilterValue,
    removeAdvancedFilterValue,
    resetAdvancedFilters,
    advancedFilterChips,
    renderHeaderLabel,
    renderSortableHeader,
  } = productFilters;
  const {
    isWaitingForLocalApiServerPage,
    visibleProductStatusCounts,
    filteredProducts,
    productPagination,
    totalPages,
    isProductPageRenderPending,
    renderedPageProducts,
    pageProductKeys,
    selectedProducts,
    allPageSelected,
    pageSelectionIndeterminate,
    batchPopoverOpen,
  } = useProductPaginationState({
    productSort,
    productListQueryFilterSignature,
    localProductServerPageMeta,
    productMirrorScopeKey,
    status,
    keyword,
    pageSize,
    page,
    products,
    localProductMirrorStatusCounts,
    productPerformance,
    loading,
    selectedProductKeys,
    batchAnchorEl,
    setPage,
    setSelectedProductKeys,
    setProducts,
  });
  const {
    toggleProductSelection,
    togglePageSelection,
    resolveWritableOzonProduct,
    handleEditProduct,
    getProductSourceRecord,
    getProductSourceSelectedSlot,
    getProductSourceLinkValue,
    selectProductSourceSlot,
    updateProductSourceLink,
    saveProductSourceLink,
    refreshProductMaterialViews,
    handleReadProductBusMeasurement,
  } = useProductSourceMaterialState({
    setSelectedProductKeys,
    pageProductKeys,
    allPageSelected,
    activeShop,
    shops,
    setProducts,
    setEditingProduct,
    setSavingProductId,
    setProductNotice,
    productSourceLinks,
    productSourceSlotMap,
    setProductSourceSlotMap,
    setProductSourceLinks,
    shop,
    status,
  });
  const {
    handleSaveProduct,
    handleProductArchiveAction,
    closeArchiveConfirmDialog,
    getProductArchiveOperationKey,
    pendingProductArchiveKeys,
    handleConfirmProductArchiveAction,
  } = useProductWriteState({
    editingProduct,
    setSavingProductId,
    shops,
    setProducts,
    setEditingProduct,
    setProductNotice,
    loadOzonProducts,
    resolveWritableOzonProduct,
    setArchiveConfirmDialog,
    savingProductId,
    archiveConfirmDialog,
  });
  const {
    activeBatchMeta,
    batchWarehouseOptions,
    batchWarehouseLoading,
    batchWarehouseError,
    archiveConfirmActionText,
    archiveConfirmProduct,
    archiveConfirmProductLabel,
    archiveConfirmSaving,
    openBatchDialog,
    handleConfirmBatchAction,
    productRefreshPercent,
    productThinProgressVisible,
    productThinProgressTitle,
    productTablePageBusy,
    handleProductPageChange,
  } = useProductBatchState({
    batchDialog,
    batchWarehouseState,
    shops,
    loading,
    archiveConfirmDialog,
    savingProductId,
    savedDefaultWarehouseIds,
    batchWarehouseRequestRef,
    setBatchWarehouseState,
    selectedProducts,
    setProductNotice,
    setBatchAnchorEl,
    setBatchDialog,
    setBatchSaving,
    setSavingProductId,
    refreshProductMaterialViews,
    setSelectedProductKeys,
    loadOzonProducts,
    productRefreshProgress,
    productPageLoading,
    isProductPageTransitionPending,
    isProductPageRenderPending,
    isWaitingForLocalApiServerPage,
    page,
    setProductPageLoading,
    startProductPageTransition,
    setPage,
    resolveWritableOzonProduct,
  });
  const handleOpenOzonProductPage = React.useCallback(async (product) => {
    if (!String(product?.name || product?.title || '').trim()) return;
    try {
      const target = await openOzonProductPage(product);
      if (!target.exact) {
        setProductNotice({
          open: true,
          severity: 'info',
          message: '当前商品缺少 Ozon SKU，已按商品标题打开 Ozon 搜索结果。',
        });
      }
    } catch (error) {
      setProductNotice({
        open: true,
        severity: 'error',
        message: getOzonProductPageErrorMessage(error),
      });
    }
  }, [setProductNotice]);
  return {
    isVisible,
    shops,
    activeShop,
    canReadOzon,
    shop,
    setShop,
    status,
    setStatus,
    keyword,
    setKeyword,
    loading,
    productLoadError,
    editingProduct,
    setEditingProduct,
    savingProductId,
    productNotice,
    setProductNotice,
    page,
    pageSize,
    setPageSize,
    selectedProductKeys,
    batchAnchorEl,
    setBatchAnchorEl,
    batchDialog,
    setBatchDialog,
    archiveConfirmDialog,
    batchSaving,
    advancedFilterAnchorEl,
    setAdvancedFilterAnchorEl,
    advancedFilters,
    productRefreshProgress,
    handleRefreshProducts,
    advancedFilterOpen,
    hasAdvancedFilters,
    advancedFilterGroups,
    toggleAdvancedFilterValue,
    removeAdvancedFilterValue,
    resetAdvancedFilters,
    advancedFilterChips,
    renderHeaderLabel,
    renderSortableHeader,
    visibleProductStatusCounts,
    filteredProducts,
    productPagination,
    totalPages,
    renderedPageProducts,
    pageProductKeys,
    selectedProducts,
    allPageSelected,
    pageSelectionIndeterminate,
    batchPopoverOpen,
    toggleProductSelection,
    togglePageSelection,
    handleEditProduct,
    getProductSourceRecord,
    getProductSourceSelectedSlot,
    getProductSourceLinkValue,
    selectProductSourceSlot,
    updateProductSourceLink,
    saveProductSourceLink,
    handleReadProductBusMeasurement,
    handleSaveProduct,
    handleProductArchiveAction,
    closeArchiveConfirmDialog,
    getProductArchiveOperationKey,
    pendingProductArchiveKeys,
    handleConfirmProductArchiveAction,
    activeBatchMeta,
    batchWarehouseOptions,
    batchWarehouseLoading,
    batchWarehouseError,
    archiveConfirmActionText,
    archiveConfirmProduct,
    archiveConfirmProductLabel,
    archiveConfirmSaving,
    openBatchDialog,
    handleConfirmBatchAction,
    productRefreshPercent,
    productThinProgressVisible,
    productThinProgressTitle,
    productTablePageBusy,
    handleProductPageChange,
    handleOpenOzonProductPage,
  };
}
