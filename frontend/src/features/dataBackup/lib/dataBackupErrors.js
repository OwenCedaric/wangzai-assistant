export function getDataBackupErrorMessage(code, fallback = '操作失败，请重试。') {
  return ERROR_MESSAGES[String(code || '').trim()] || fallback;
}

export function presentDataBackupError(error, fallback) {
  const code = String(error?.code || '').trim();
  if (code) return getDataBackupErrorMessage(code);
  if (error instanceof Error && error.message && !/^[A-Z][A-Z0-9_:-]+$/u.test(error.message)) {
    return error.message;
  }
  return fallback || '操作失败，请重试。';
}
